"""``python -m fsg_common.gate_table`` (crm#2815 item 7).

One table of every ``check_*.py`` script in a repo: where it runs, or why nothing runs it.
Moved here from the crm repo's ``scripts/gen_gate_table.py`` so every repo can run it.

    python -m fsg_common.gate_table                 # rewrite docs/gate-table.md
    python -m fsg_common.gate_table --check         # a gate wired to nothing, or a stale table

A script is WIRED when a GitHub workflow, a ``.githooks`` file, a monitor list (``--timers-module``)
or a file under ``infra/`` names it. Any other script must be in the by-hand JSON file with the
moment it is run and why it cannot be wired. Exit codes follow ``fsg_common.refused``: 0 clean,
1 findings, 2 not established (no scripts directory, by-hand file unreadable or not an object).
Nothing here records when a gate last failed; a column of guesses would read as fact.
"""
from __future__ import annotations

import argparse
import importlib
import json
import sys
from pathlib import Path

from fsg_common.refused import Refused, run_check

_INFRA_SUFFIX = {".sh", ".service", ".timer", ".yaml", ".yml", ".ps1"}


def _files(root: Path, pattern: str) -> list[Path]:
    return [p for p in sorted(root.rglob(pattern)) if p.is_file()] if root.is_dir() else []


def _text(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="replace")


def check_scripts(scripts: Path) -> list[Path]:
    return sorted(p for p in scripts.rglob("check_*.py")
                  if "fsg_common" not in p.parts and "__pycache__" not in p.parts)


def timer_names(scripts: Path, module: str | None) -> set[str]:
    """Script names a monitor list runs; ``module`` (in ``scripts``) has MONITORS."""
    if not module:
        return set()
    sys.path.insert(0, str(scripts))
    try:
        mon = importlib.import_module(module)
        return {Path(a).name for m in mon.MONITORS for a in m["argv"] if str(a).endswith(".py")}
    except (ImportError, AttributeError, KeyError, TypeError) as exc:
        raise Refused(f"cannot read the monitor list from {module}: {exc}") from exc
    finally:
        sys.path.remove(str(scripts))


def load_by_hand(path: Path) -> dict[str, str]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise Refused(f"cannot read {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise Refused(f"{path} is not a JSON object")
    return {k: v for k, v in data.items() if not k.startswith("_")}


def build(root: Path, scripts: Path, by_hand_path: Path,
          timers_module: str | None = None) -> tuple[list[dict], list[str]]:
    if not scripts.is_dir():
        raise Refused(f"no scripts directory at {scripts}")
    by_hand = load_by_hand(by_hand_path)
    timer = timer_names(scripts, timers_module)
    workflows = _files(root / ".github" / "workflows", "*.yml")
    hooks = _files(root / ".githooks", "*")
    infra = [p for p in _files(root / "infra", "*") if p.suffix in _INFRA_SUFFIX]
    rows, problems, seen = [], [], set()
    for path in check_scripts(scripts):
        name = path.name
        seen.add(name)
        vehicles = []
        wf = [p.name for p in workflows if name in _text(p)]
        if wf:
            vehicles.append("CI: " + ", ".join(wf))
        if any(name in _text(p) for p in hooks):
            vehicles.append("pre-commit hook")
        if name in timer:
            vehicles.append("monitor timer")
        inf = [str(p.relative_to(root)).replace("\\", "/") for p in infra if name in _text(p)]
        if inf:
            vehicles.append("infra: " + ", ".join(inf))
        if vehicles:
            if name in by_hand:
                problems.append(f"{name} is listed by hand but is wired "
                                f"({'; '.join(vehicles)}) -- remove the stale entry")
            rows.append({"name": name, "vehicle": "; ".join(vehicles), "why": ""})
        elif name in by_hand:
            rows.append({"name": name, "vehicle": "BY HAND", "why": by_hand[name]})
        else:
            problems.append(f"{name} is wired to no workflow, hook, monitor or infra file "
                            "and is not in the by-hand file -- wire it, or list it there "
                            "with the moment it runs and why it cannot be wired")
            rows.append({"name": name, "vehicle": "NOTHING", "why": ""})
    for name in by_hand:
        if name not in seen:
            problems.append(f"the by-hand file lists {name}, which does not exist")
    return rows, problems


def render(rows: list[dict]) -> str:
    out = ["# Gate table", "",
           "Generated by `python -m fsg_common.gate_table` -- do not edit by hand. Every "
           "`check_*.py` script and where it runs; `BY HAND` rows carry the moment and "
           "the reason, from the by-hand JSON file. `--check` (CI) fails on a "
           "gate wired to nothing. When a gate last failed is not recorded anywhere in "
           "the repo, so this table does not claim it.", "",
           "| Script | Where it runs | Why by hand |", "| --- | --- | --- |"]
    for r in rows:
        out.append(f"| `{r['name']}` | {r['vehicle']} | {r['why']} |")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m fsg_common.gate_table")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 on a finding")
    ap.add_argument("--root", default=".")
    ap.add_argument("--scripts", default="scripts")
    ap.add_argument("--by-hand", default="scripts/gates_by_hand.json")
    ap.add_argument("--table", default="docs/gate-table.md")
    ap.add_argument("--timers-module", default=None,
                    help="module in --scripts with a MONITORS list of {'argv': [...]}")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    table = root / a.table

    def run() -> list[str]:
        rows, problems = build(root, root / a.scripts, root / a.by_hand, a.timers_module)
        text = render(rows)
        if a.check:
            current = (table.read_text(encoding="utf-8").replace("\r\n", "\n")
                       if table.exists() else "")
            if current != text:
                problems.append(f"{a.table} is stale -- run python -m fsg_common.gate_table")
        else:
            table.parent.mkdir(parents=True, exist_ok=True)
            table.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {a.table} ({len(rows)} gates)")
        return problems

    return run_check(run)


if __name__ == "__main__":
    sys.exit(main())
